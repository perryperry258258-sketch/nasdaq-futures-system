// 美股（NYSE/Nasdaq）全天休市的國定假日清單。
//
// 用途：回踩策略的Reference Candle綁定「美股09:30 ET開盤」這個事件，國定假日當天
// 美股根本沒有開盤，不該被當成有效的交易日去找Reference Candle——這裡列出完整
// 日期，跟WEEKDAYS（週一到週五）檢查一起用。
//
// 資料來源：NYSE官方公告（2026-09查證），只列「全天休市」的日子，不包含提前收盤的
// 日子（例如感恩節隔天、聖誕夜提前收盤到下午1點）——提前收盤當天09:30還是正常開盤，
// Reference Candle的60分鐘觀察窗口在提前收盤前就結束了，不影響判斷，不需要排除。
//
// 【誠實揭露：這份清單只到2026年底】NYSE通常在前一年公告完整年度假日行事曆，
// 2027年的日期目前還沒有查證到完整、可信的版本，先不寫進來，避免寫錯日期。
// 每年年底記得回來更新這份清單，加上下一年度的日期，不然過了2026年12月31日之後，
// 系統會誤判2027年的假日成有效交易日。
export const US_MARKET_HOLIDAYS_2026 = new Set([
  "2026-01-01", // 元旦
  "2026-01-19", // 馬丁路德金紀念日
  "2026-02-16", // 華盛頓誕辰日
  "2026-04-03", // 耶穌受難日
  "2026-05-25", // 陣亡將士紀念日
  "2026-06-19", // 六月節
  "2026-07-03", // 獨立日（7/4是週六，提前到週五）
  "2026-09-07", // 勞動節
  "2026-11-26", // 感恩節
  "2026-12-25", // 聖誕節
]);

export function isUsMarketHoliday(year: number, month: number, day: number): boolean {
  const key = `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
  return US_MARKET_HOLIDAYS_2026.has(key);
}
